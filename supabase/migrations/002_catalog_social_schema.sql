-- Persistent catalogue, supplier, messaging and social-publication schema.
-- Every object is guarded so this can be applied to an existing project.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  email text not null default '',
  city text not null default '',
  brand_name text not null default '',
  bank_name text,
  rib_number text,
  payment_method text,
  role text not null default 'affiliate',
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null default '',
  email text not null default '',
  address text not null default '',
  city text not null default '',
  category text not null default '',
  notes text not null default '',
  products jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  key text not null unique,
  label_fr text not null,
  label_ar text not null default '',
  icon text not null default '📦',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.delivery_agencies (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null default '',
  email text not null default '',
  wilayas_covered jsonb not null default '[]'::jsonb,
  price_per_kg numeric(10, 2) not null default 0,
  delivery_delay text not null default '',
  tracking_url text not null default '',
  notes text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default '',
  image_url text not null default '',
  wholesale_price numeric(10, 2) not null default 0,
  suggested_price numeric(10, 2) not null default 0,
  affiliate_margin numeric(10, 2) not null default 0,
  description text not null default '',
  delivery_cost numeric(10, 2) not null default 0,
  in_stock boolean not null default true,
  supplier_id bigint references public.suppliers(id) on delete set null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.product_media (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  public_url text,
  storage_path text,
  alt_text text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.telegram_messages (
  id uuid primary key default gen_random_uuid(),
  telegram_message_id text,
  supplier_id bigint references public.suppliers(id) on delete set null,
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'received',
  error text,
  received_at timestamptz not null default now(),
  processed_at timestamptz
);

create table if not exists public.social_publications (
  id uuid primary key default gen_random_uuid(),
  product_id bigint references public.products(id) on delete set null,
  platform text not null,
  destination text,
  content text not null default '',
  status text not null default 'draft',
  external_post_id text,
  scheduled_at timestamptz,
  published_at timestamptz,
  error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


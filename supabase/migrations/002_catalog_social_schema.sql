create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public, anon, authenticated;

alter table public.profiles enable row level security;
alter table public.suppliers enable row level security;
alter table public.categories enable row level security;
alter table public.delivery_agencies enable row level security;
alter table public.products enable row level security;
alter table public.product_media enable row level security;
alter table public.telegram_messages enable row level security;
alter table public.social_publications enable row level security;
alter table public.orders enable row level security;
alter table public.withdrawals enable row level security;

drop policy if exists profiles_owner_or_admin on public.profiles;
create policy profiles_owner_or_admin on public.profiles
  for all to authenticated
  using (auth.uid() = id or public.is_admin())
  with check (auth.uid() = id or public.is_admin());

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'suppliers', 'categories', 'delivery_agencies', 'products',
    'product_media', 'telegram_messages', 'social_publications'
  ] loop
    execute format('drop policy if exists %I on public.%I', table_name || '_authenticated_read', table_name);
    execute format(
      'create policy %I on public.%I for select to authenticated using (true)',
      table_name || '_authenticated_read', table_name
    );
    execute format('drop policy if exists %I on public.%I', table_name || '_admin_write', table_name);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      table_name || '_admin_write', table_name
    );
  end loop;
end $$;

